// Pieces of the agent-file format shared by every host's renderer (plan 5.2, decision 0014).
export const AGENT_MARKER = 'Generated by go-getter apply';

// Instruction text shared by every host's format.
export function roleBody(roster, role) {
  const lines = [role.instructions];
  if (role.note) lines.push(role.note);
  if (roster.handoff) lines.push(`Handoff: ${roster.handoff}`);
  if (roster.escalation) lines.push(`Escalation: ${roster.escalation}`);
  return lines.join('\n\n');
}

export const tag = (roster, role) => `${AGENT_MARKER} from ${roster.decision}; do not edit. role=${role.id} task-class=${role['task-class']}`;

export function md(head, roster, role, extraYaml = '') {
  const lines = Object.entries(head).map(([k, v]) => `${k}: ${typeof v === 'string' && !/^[A-Za-z][A-Za-z0-9 ,-]*$/.test(v) ? JSON.stringify(v) : v}`);
  return `---\n${lines.join('\n')}${extraYaml}\n---\n\n${roleBody(roster, role)}\n\n<!-- ${tag(roster, role)} -->\n`;
}
