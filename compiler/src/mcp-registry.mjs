// The MCP tool registry (decision 0139 item 2): the tools declared by the packs a project adopted, and no others.
import { readArtifacts } from './artifacts.mjs';
import { listPackFiles, loadPack } from './packs.mjs';

// JSON Schema for a tool's arguments, built from a declaration's ids and enumerated values.
export function inputSchema(tool) {
  const properties = {};
  for (const [name, p] of Object.entries(tool.input ?? {})) {
    properties[name] = p.type === 'enum' ? { type: 'string', enum: p.values } : { type: 'string', pattern: '^[A-Za-z0-9][A-Za-z0-9._-]*$' };
    if (p.description) properties[name].description = p.description;
  }
  const required = Object.entries(tool.input ?? {}).filter(([, p]) => p.required).map(([n]) => n);
  return { type: 'object', properties, ...(required.length ? { required } : {}), additionalProperties: false };
}

// Ids of the packs the project adopted (an active artifact generated by the pack).
export function adoptedPackIds(project) {
  const ids = new Set();
  for (const a of readArtifacts(project)) {
    const by = a.data['go-getter']?.['generated-by'];
    if (a.data.status === 'active' && by) ids.add(String(by).split('@')[0]);
  }
  return ids;
}

// { tools, errors }: the declared tools of the adopted packs. `packs` is { id: packJson } (default: the shipped packs).
// A declaration naming a function off the read-only list, or a name two packs both declare, is an error and is not listed.
export function mcpRegistry(project, root, packs = Object.fromEntries(listPackFiles(root).map((f) => loadPack(f)).map((p) => [p.id, p]))) {
  const tools = [];
  const errors = [];
  const taken = new Map();
  for (const id of [...adoptedPackIds(project)].sort()) {
    for (const [i, t] of (packs[id]?.mcp ?? []).entries()) {
      const at = `${id}.mcp[${i}]`;
      if (taken.has(t.name)) {
        errors.push(`${at}.name: "${t.name}" is already declared by pack "${taken.get(t.name)}"`);
        continue;
      }
      taken.set(t.name, id);
      tools.push({ name: t.name, description: t.description, inputSchema: inputSchema(t), function: t.function, class: t.class, pack: id });
    }
  }
  return { tools, errors };
}
