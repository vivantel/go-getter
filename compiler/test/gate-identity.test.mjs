import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, symlinkSync, realpathSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { evaluatePreTool, respond } from '../src/hook.mjs';
import { gateEntries, goGetterSpellings } from '../src/gate.mjs';
import { collectEnforcement } from '../src/enforce.mjs';

const cli = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'bin', 'go-getter.mjs');

// A project that gates `plan issue create|comment|close` by what a call runs, with go-getter reachable five ways.
function setup() {
  const base = realpathSync(mkdtempSync(path.join(tmpdir(), 'gg-identity-')));
  const dir = path.join(base, 'proj');
  mkdirSync(path.join(dir, 'docs/guardrails'), { recursive: true });
  mkdirSync(path.join(dir, '.go-getter/bin'), { recursive: true });
  writeFileSync(path.join(dir, '.go-getter/bin/go-getter'), '#!/bin/sh\n# Generated by go-getter apply; do not edit.\nexit 0\n', { mode: 0o755 });
  writeFileSync(path.join(dir, 'docs/guardrails/tracker-writes.md'), `---\nid: tracker-writes\ntitle: tracker writes\nstatus: active\ndate: 2026-10-11\ntags: [guardrail]\ngo-getter:\n  enforcement:\n    - tier: 2\n      check: "writes ask"\n      run: 'builtin:gate-command classes="" go-getter="plan issue create,plan issue comment,plan issue close"'\n---\n\n## Guardrail\n\nAsk.\n`);
  const bin = path.join(base, 'bin');
  mkdirSync(bin);
  symlinkSync(cli, path.join(bin, 'go-getter'));
  mkdirSync(path.join(base, 'other'));
  writeFileSync(path.join(base, 'other/go-getter'), '#!/bin/sh\necho not go-getter\n', { mode: 0o755 });
  const savedPath = process.env.PATH;
  process.env.PATH = `${bin}${path.delimiter}${savedPath}`;
  return {
    base,
    dir,
    run: (command, host = 'claude-code') => evaluatePreTool(dir, { tool_name: 'Bash', tool_input: { command } }, host === 'none' ? undefined : host),
    cleanup: () => {
      process.env.PATH = savedPath;
      rmSync(base, { recursive: true, force: true });
    },
  };
}

test('every way of running go-getter is asked about on a host whose hook can ask', () => {
  const s = setup();
  try {
    for (const command of [
      'go-getter plan issue create 6', '.go-getter/bin/go-getter plan issue comment 3 --text hi', './.go-getter/bin/go-getter plan issue close 3', `${cli} plan issue create 2`,
      `node ${cli} plan issue close 2`, 'npx -y go-getter plan issue create 6', 'ls && go-getter plan issue create 6', 'go-getter plan issue comment 3 --text "two words"',
      'sh -c "echo" ; go-getter plan issue close 4 docs/plans/x.md', 'go-getter plan issue create "6',
    ]) {
      const d = s.run(command);
      assert.equal(d.ask, true, command);
      assert.equal(d.deny, false, command);
    }
    const asked = s.run('go-getter plan issue create 6');
    const out = respond('claude-code', asked);
    assert.equal(JSON.parse(out.stdout).hookSpecificOutput.permissionDecision, 'ask');
    assert.match(asked.reason, /go-getter plan issue create writes outside this machine: approve "go-getter plan issue create 6"\?/);
  } finally {
    s.cleanup();
  }
});

test('reads, dry runs, other subcommands and lookalikes are not gated', () => {
  const s = setup();
  try {
    for (const command of [
      'go-getter plan issue --dry-run create 6', 'go-getter plan status', 'go-getter plan issue', 'go-getter plan next docs/plans/x.md', 'go-getter secret run --from a -- b',
      'echo go-getter plan issue create 6', 'git commit -m "plan issue create"', 'grep "plan issue create" docs/x.md', 'go-getter-x plan issue create 6', `${path.join(s.base, 'other/go-getter')} plan issue create 6`,
      'npx other-package plan issue create 6', 'ls', 'gh issue create --title x',
    ]) assert.deepEqual(s.run(command), { deny: false }, command);
  } finally {
    s.cleanup();
  }
});

test('a host that cannot ask hands over, a host with native ask rules relies on them, and no known host is not gated', () => {
  const s = setup();
  try {
    const command = 'go-getter plan issue create 6';
    for (const host of ['codex', 'cursor', 'gemini-cli', 'copilot']) {
      const d = s.run(command, host);
      assert.equal(d.deny, true, host);
      assert.equal(d.ask, undefined, host);
      assert.match(d.reason, /is an outward command and needs a human; ask the user to run it themselves/);
    }
    for (const host of ['kilo', 'opencode']) assert.deepEqual(s.run(command, host), { deny: false }, `${host}: the glob rules apply wrote prompt`);
    assert.deepEqual(s.run(command, 'none'), { deny: false });
    assert.equal(respond('codex', { deny: false, ask: true, reason: 'x' }).stdout, '', 'ask is never sent to a host that would run the call anyway');
  } finally {
    s.cleanup();
  }
});

test('the gate entries name subcommands, validate them, and list the spellings a checkout adds', () => {
  const s = setup();
  try {
    const entries = collectEnforcement(s.dir);
    const gated = gateEntries(entries, { project: s.dir });
    assert.deepEqual(gated.map((g) => g.id), ['go-getter:plan issue create', 'go-getter:plan issue comment', 'go-getter:plan issue close']);
    assert.deepEqual(goGetterSpellings(s.dir), ['go-getter', '.go-getter/bin/go-getter', './.go-getter/bin/go-getter', 'npx go-getter', 'npx -y go-getter']);
    const bad = [{ tier: 2, guardrail: 'g', parsed: { kind: 'builtin', id: 'gate-command', args: { classes: '', 'go-getter': 'plan issue create;rm' } } }];
    assert.throws(() => gateEntries(bad), /go-getter must be subcommand words/);
    assert.throws(() => gateEntries([{ tier: 2, guardrail: 'g', parsed: { kind: 'builtin', id: 'gate-command', args: { classes: '' } } }]), /gate-command classes must be/);
  } finally {
    s.cleanup();
  }
});
