import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, symlinkSync, chmodSync, rmSync, realpathSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { parseSimpleCommand, goGetterCall, goGetterCommand, isGoGetterEntry } from '../src/invocation.mjs';

const words = (command) => parseSimpleCommand(command).words;
const simple = (command) => parseSimpleCommand(command).simple;

test('quotes and escapes are resolved into words', () => {
  assert.deepEqual(words('a "b c" d'), ['a', 'b c', 'd']);
  assert.deepEqual(words("a 'b $c' d"), ['a', 'b $c', 'd']);
  assert.deepEqual(words('a b\\ c'), ['a', 'b c']);
  assert.deepEqual(words('say "he said \\"hi\\""'), ['say', 'he said "hi"']);
  assert.deepEqual(words('a "" b'), ['a', '', 'b']);
  assert.deepEqual(words('x --from=".env" y'), ['x', '--from=.env', 'y']);
  assert.equal(simple('git commit -m "mentions .env and a;b|c"'), true, 'operators inside quotes are only text');
});

test('anything that could run something else is not a simple command', () => {
  const cases = {
    'a | b': 'pipe', 'a || b': 'or', 'a && b': 'and', 'a ; b': 'list', 'a & b': 'background', 'a > f': 'redirect', 'a < f': 'input', 'a <<EOF': 'heredoc',
    'a $HOME': 'expansion', 'a "$HOME"': 'expansion in double quotes', 'a $(b)': 'substitution', 'a `b`': 'backtick', 'a (b)': 'subshell', '# a': 'comment',
    'FOO=bar a': 'assignment', 'a "b': 'open double quote', "a 'b": 'open single quote', 'a\nb': 'second line', 'a\\': 'trailing backslash', '': 'empty', '   ': 'blank',
  };
  for (const [command, why] of Object.entries(cases)) assert.equal(simple(command), false, `${why}: ${JSON.stringify(command)}`);
  assert.equal(simple("a '$HOME' b"), true, 'a dollar inside single quotes is literal');
  assert.equal(simple('a b#c'), true, 'a hash inside a word is not a comment');
});

// A go-getter checkout, a project runner, a user-level link and some lookalikes, each in its own directory.
function layout() {
  const root = realpathSync(mkdtempSync(path.join(tmpdir(), 'gg-invocation-')));
  const make = (rel, text = '', mode) => {
    const file = path.join(root, rel);
    mkdirSync(path.dirname(file), { recursive: true });
    writeFileSync(file, text);
    if (mode) chmodSync(file, mode);
    return file;
  };
  make('pkg/package.json', '{"name":"go-getter"}');
  const entry = make('pkg/compiler/bin/go-getter.mjs', '#!/usr/bin/env node\n', 0o755);
  make('proj/.go-getter/bin/go-getter', '#!/bin/sh\n# Generated by go-getter apply; do not edit.\n', 0o755);
  mkdirSync(path.join(root, 'home/.local/bin'), { recursive: true });
  symlinkSync(entry, path.join(root, 'home/.local/bin/go-getter'));
  make('other/package.json', '{"name":"other"}');
  make('other/go-getter.mjs', '', 0o755);
  make('other/bin/go-getter', '#!/bin/sh\necho not go-getter\n', 0o755);
  make('other/bin/go-getter-x', '', 0o755);
  return { root, entry, cleanup: () => rmSync(root, { recursive: true, force: true }) };
}

test('go-getter is recognised wherever it is installed', () => {
  const l = layout();
  const home = path.join(l.root, 'home');
  const cwd = path.join(l.root, 'proj');
  const env = { PATH: `${path.join(home, '.local/bin')}${path.delimiter}/usr/bin` };
  const savedHome = process.env.HOME;
  process.env.HOME = home;
  try {
    const call = (command) => goGetterCommand(command, { cwd, env });
    assert.deepEqual(call('go-getter secret run --from a -- b'), { via: 'path', args: ['secret', 'run', '--from', 'a', '--', 'b'] }, 'a user-level go-getter on PATH');
    assert.deepEqual(call('.go-getter/bin/go-getter plan next'), { via: 'runner', args: ['plan', 'next'] }, 'the project runner, relative');
    assert.equal(call(`${path.join(cwd, '.go-getter/bin/go-getter')} plan next`).via, 'runner', 'the project runner, absolute');
    assert.equal(call('./.go-getter/bin/go-getter plan next').via, 'runner');
    assert.equal(call('~/.local/bin/go-getter plan next').via, 'path', 'a path under the home directory');
    assert.equal(call(`${l.entry} plan next`).via, 'path', 'the entry script itself');
    assert.deepEqual(call(`node ${l.entry} secret run`), { via: 'node', args: ['secret', 'run'] });
    assert.deepEqual(call(`node --no-warnings ${l.entry} secret run`), { via: 'node', args: ['secret', 'run'] });
    assert.equal(call('node ../pkg/compiler/bin/go-getter.mjs plan next').via, 'node', 'relative to the working directory');
    assert.deepEqual(call('npx -y go-getter plan next'), { via: 'npx', args: ['plan', 'next'] });
    assert.deepEqual(call('npx go-getter@0.3.0 plan next'), { via: 'npx', args: ['plan', 'next'] });
    assert.equal(call('npx github:vivantel/go-getter#v0.3.0 plan next').via, 'npx');
    assert.equal(call('go-getter secret run --from ".env" -- node "a b"').args.at(-1), 'a b', 'quoted arguments are accepted');
  } finally {
    process.env.HOME = savedHome;
    l.cleanup();
  }
});

test('lookalikes, a missing install and a non-simple command are not go-getter', () => {
  const l = layout();
  const cwd = path.join(l.root, 'proj');
  const other = path.join(l.root, 'other');
  const env = { PATH: `${path.join(other, 'bin')}${path.delimiter}/usr/bin` };
  try {
    const call = (command, e = env) => goGetterCommand(command, { cwd, env: e });
    assert.equal(call('go-getter plan next'), null, 'a go-getter on PATH that is not go-getter');
    assert.equal(call('go-getter-x plan next'), null);
    assert.equal(call(`node ${path.join(other, 'go-getter.mjs')} plan next`), null, 'an entry of another package');
    assert.equal(call('npx go-getter-extra plan next'), null);
    assert.equal(call('npx other-package plan next'), null);
    assert.equal(call('node nowhere.mjs'), null);
    assert.equal(call('go-getter plan next', { PATH: '/nonexistent' }), null, 'no go-getter at all');
    assert.equal(call(`${l.entry} plan next | cat`), null, 'a pipeline');
    assert.equal(call(`${l.entry} plan next; rm -rf x`), null, 'a list');
    assert.equal(call(`${l.entry} plan $(echo next)`), null, 'a substitution');
    assert.equal(call(`PATH=/evil ${l.entry} plan next`), null, 'a variable assignment');
    assert.equal(goGetterCall([], { cwd, env }), null);
    assert.equal(isGoGetterEntry(path.join(l.root, 'does-not-exist')), false);
    assert.equal(isGoGetterEntry(path.join(l.root, 'proj')), false, 'a directory');
  } finally {
    l.cleanup();
  }
});
